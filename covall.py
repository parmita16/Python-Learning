#assignment 20 covariance and correlation all in one
import numpy as np
import matplotlib.pyplot as plt
a1=np.array([2,4,5,6,7,8,9,10])
b1=np.array([55,60,65,70,75,80,85,90])
a2=np.array([0,50,100,150,200,250,300,350])
b2=np.array([60,75,88,95,92,80,65,40])
a3=np.array([2,4,5,6,7,8,9,10])
b3=np.array([90,85,80,75,70,65,60,55])
print("Dataset 1")
print("Covariance =",np.cov(a1,b1)[0,1])
print("Correlation =",np.corrcoef(a1,b1)[0,1])
print("\nDataset 2")
print("Covariance =",np.cov(a2,b2)[0,1])
print("Correlation =",np.corrcoef(a2,b2)[0,1])
print("\nDataset 3")
print("Covariance =",np.cov(a3,b3)[0,1])
print("Correlation =",np.corrcoef(a3,b3)[0,1])
plt.figure(figsize=(7,5))
plt.plot(a1,b1,color="red",marker="o",label="Dataset 1")
plt.plot(a2,b2,color="blue",marker="s",label="Dataset 2")
plt.plot(a3,b3,color="green",marker="^",label="Dataset 3")
plt.xlabel("A")
plt.ylabel("B")
plt.title("Covariance and Correlation")
plt.legend()
plt.grid(True)
plt.show()